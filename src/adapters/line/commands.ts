/**
 * LINE で受け付けるコマンドの判定。
 *
 * ★リッチメニュー（assets/richmenu.json）が送ってくる文言と、
 *   ここの判定がずれるとボタンが無反応になる。
 *   ずれを起こさないよう、判定はこの1枚に集約して
 *   test/unit/richmenu.test.ts で突き合わせている。
 *
 * ★リッチメニューは配布する全員で同じものを使う。
 *   文言を変えるときは、画像・assets/richmenu.json・ここの3つを同時に直すこと。
 */

export const COMMANDS = {
  /** メニューを出す */
  menu: /^(メニュー|めにゅー|ヘルプ|help|使い方)$/i,

  /** 記事作成モードに入る（リッチメニュー左） */
  newArticle: /^(記事を作成する|記事作成|記事を作る|新規作成|新しい記事)$/,

  /**
   * ナレッジ（リッチメニュー中央）
   * ★画像には「プロフィール登録」と刷ってあるので、その文言も受ける
   */
  knowledge: /^(プロフィールを登録する|プロフィール登録|プロフィール|設定|自己紹介|私について|コンテキスト|ナレッジ|ナレッジ登録|メモ|知識|前提)$/,

  /** 過去記事一覧（リッチメニュー右） */
  articleList: /^(過去記事一覧・修正|過去記事一覧|過去記事|記事一覧|一覧|履歴|過去の記事)$/,

  /** note 連携 */
  connect: /^(note連携|noteを連携|noteと連携|note連携する|note接続|連携|再連携|つなぎ直す|note再連携)$/i,
  connectStatus: /^(連携状況|連携確認|note連携状況|接続状況|note状況)$/i,
  disconnect: /^(連携解除|note連携解除|連携を解除)$/i,

  /** AI まわりの設定（調べ方・画像・サムネ。リッチメニュー下段左。持ち主だけ） */
  aiSettings: /^(AI設定|AIの設定|ai設定)$/i,

  /** 連携状況・投稿者・設定画面への入り口（リッチメニュー下段右） */
  moreSettings: /^(その他の設定|その他|その他設定)$/,

  /** サムネイル自動生成の設定（持ち主だけ） */
  thumbSettings: /^(サムネ設定|サムネ自動生成|サムネイル設定|サムネの設定|サムネ自動)$/,

  /** 投稿の設定 */
  settings: /^(投稿設定|投稿の設定|制限設定|投稿制限|上限設定|投稿方法)$/,

  /**
   * セットアップ画面を実行するための使い捨てコードを出す。
   * ★2回目以降のセットアップは、このコードが無いと実行できない
   *   （画面のURLを知っただけの第三者に設定を触らせないため）
   */
  setupCode: /^(セットアップ|セットアップコード|再セットアップ|設定コード)$/,

  /**
   * 持ち主の登録をやめる。次に話しかけた人が新しい持ち主になる。
   * ★人に引き継ぐとき、誤って別の人が持ち主になったときの戻し方。
   */
  ownerReset: /^(持ち主をリセット|持ち主の変更|オーナー変更|オーナーをリセット|引き継ぎ)$/,

  /**
   * 投稿者（スタッフ）を追加する。10分以内に最初に話しかけた1人が投稿者になる。
   * ★持ち主だけが実行できる。
   */
  memberAdd: /^(投稿者を追加|投稿者追加|投稿者を増やす|スタッフを追加|スタッフ追加|メンバーを追加|メンバー追加)$/,

  /** 投稿者の一覧を見る・外す（持ち主だけ） */
  memberList: /^(投稿者一覧|投稿者の一覧|投稿者を外す|投稿者を削除|スタッフ一覧|スタッフを外す|メンバー一覧)$/,

  /**
   * 確認待ちの人を、ボタンではなく文字で承認する・断る（持ち主だけ）。
   * ★2026-09-15 実際に「投稿者にする」がボタンの合図ではなく文字で届き、登録されなかった。
   *   確認待ちが無いときの「断る」は、ふつうのメッセージとして扱う（ここで横取りしない）。
   */
  memberApprove: /^(投稿者にする)$/,
  memberReject: /^(断る)$/,
} as const;

export type CommandName = keyof typeof COMMANDS;
