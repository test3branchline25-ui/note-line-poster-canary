/**
 * 記事の「担当」をいつ引き受けてよいか。
 *
 * ★なぜ要るか（2026-09-13 源蔵レビュー 必須条件1）:
 *   同じアカウントを2人で使うので、「修正する」を押した人に記事の担当を移している。
 *   ところが、自分の記事が確認待ちのまま**別の人の記事の担当も引き受けられる**と、
 *   1人が作業中の記事を2本持つ。続けて送った「タイトルを変えて」「OK」は、
 *   作業中の記事のうち**新しいほう**に届くので、
 *   **開いたつもりの記事ではなく、もう一方の記事が書き換わり、公開される**（取り消せない）。
 *
 * → 作業中の記事が別にあるなら、ほかの記事の担当は引き受けない。先に片付けてもらう。
 */

/**
 * いま手を付けている「別の」記事を返す。無ければ null（＝引き受けてよい）。
 *
 * @param mine    その人のいま作業中の記事（無ければ null）
 * @param targetId これから担当しようとしている記事
 */
export function otherWorkInProgress<T extends { id: string }>(mine: T | null, targetId: string): T | null {
  return mine && mine.id !== targetId ? mine : null;
}
